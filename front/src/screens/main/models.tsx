export type GetChatsOptions = {
    preserveActiveChat?: boolean;
};

export interface MainContextType {
    chats: Chat[];
    chatsLoading: boolean;
    activeChatID: string | null;
    activeChat: Chat | null;
    getChats: (options?: GetChatsOptions) => Promise<void>;
    createNewChat: () => void;
    renameChat: (chatId: string, newTitle: string) => Promise<void>;
    setChatIcon: (chatId: string, icon: string) => Promise<void>;
    deleteChat: (chatId: string) => Promise<void>;
    setActiveChatID: (id: string | null) => void;
    sidebarFilter: string;
    setSidebarFilter: (filter: string) => void;
    activePluginView: string | null;
    setActivePluginView: (view: string | null) => void;
    activePluginIntegrationId: string | null;
    setActivePluginIntegrationId: (id: string | null) => void;
    rightSidebarVisible: boolean;
    setRightSidebarVisible: (visible: boolean) => void;
    isNewSession: boolean;
    setIsNewSession: (v: boolean) => void;
    /** Text auto-sent into the next new chat session (share extension, proactive Discuss). */
    pendingInitialMessage: string | null;
    setPendingInitialMessage: (msg: string | null) => void;
    closePluginKeepSidebar: () => void;
    closePluginWithSidebar: () => void;
    /** The user's Updates chat ID sourced from user.updates_chat_id, or null if not yet set. */
    updatesChatId: string | null;
}

export type Chat = {
    id: string;
    model: string;
    title: string;
    mode: 'agent' | 'team'; // 'agent' or 'team'
    team_id: string | null; // null for agent mode
    created_at: number;
    updated_at: number;
    archived_at: number | null;
    deleted_at: number | null;
    project_id?: string | null;
    messages: Message[];
    icon?: string;
    /** 'standard' for regular chats, 'updates' for the proactive Updates chat */
    chat_type?: 'standard' | 'updates';
};

export type Attachment = {
    id: string;
    file_name: string;
    file_type: string;
    size: number;
    content?: string;
    uri?: string;
};

export type MessageAction = {
    label: string;
    command: string;
    url?: string | null;
    route_url?: string | null;
    prompt?: string | null;
    agent?: string;
    why?: string;
};

// Content part types for inline tool call rendering
export type TextPart = {
    type: 'text';
    text: string;
};

export type ToolCallPart = {
    type: 'tool_call';
    tool_call: any;
};

export type ReasoningPart = {
    type: 'reasoning';
    reasoning: string;
};

export type ContentPart = TextPart | ToolCallPart | ReasoningPart;

/** Proactive event metadata attached to assistant messages in the Updates chat. */
export type ProactiveMeta = {
    source?: 'proactive';
    event_id?: string;
    event_type?:
        | 'calendar_upcoming'
        | 'email_new'
        | 'reminder_due'
        | 'daily_brief'
        | 'health_anomaly'
        | 'watch_reminder';
    /** Native URL scheme or nomi:// route to open the underlying object, if any. */
    deep_link?: string;
    /** Command call metadata for rendering command history bubbles. */
    command_call?: boolean;
    name?: string;
    args?: Record<string, any>;
};

export type Message = {
    id: string;
    chat_id: string;
    sender: string;
    role: string;
    text: string;
    agent_id?: string; // For multi-agent teams
    created_at: number;
    actions?: MessageAction[];
    importance?: string;
    metadata?: Record<string, any>;
    tool_calls?: any[];
    reasoning_steps?: string[]; // Reasoning/thinking content
    content_parts?: ContentPart[]; // For inline tool call rendering
    model?: string;
    attachments?: Attachment[];
    context_items?: any[]; // Context items (emails, documents, etc.)
    /** Last processed stream chunk index (ix); used for dedup when same frame arrives from multiple channels. */
    _stream_ix?: number;
    /** Proactive event metadata, present when message was generated by the proactive judge worker. */
    meta?: ProactiveMeta;
    /**
     * Client-only delivery status for a user message. Not sent to the server.
     * - 'pending': sent, awaiting an assistant response
     * - 'complete': answered (assistant started) or stopped by the user
     * - 'failed': send failed or the turn timed out — eligible for reconciliation
     * Defaults to 'complete' for history loaded from the server.
     */
    status?: 'pending' | 'complete' | 'failed';
    /** Set by the server when the user stopped generation for this turn; suppresses auto-resend. */
    stopped_at?: string | null;
};

